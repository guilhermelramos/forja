//! `cargo xtask icons`: compile the original SVG strokes into deterministic egui data.
mod arc;
mod path;
mod svg;
use path::Command;
use std::path::Path;

pub fn run() -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("workspace root")?;
    let generated = generate(root)?;
    std::fs::write(root.join("crates/ui-kit/src/icons_gen.rs"), generated)
        .map_err(|error| error.to_string())?;
    println!("icons: generated original stroke table");
    Ok(())
}
fn variant(name: &str) -> String {
    name.split('-')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(ch) => format!("{}{}", ch.to_ascii_uppercase(), chars.as_str()),
                None => String::new(),
            }
        })
        .collect()
}
fn number(value: f64) -> String {
    let value = if value.abs() < 0.000005 { 0.0 } else { value };
    let rounded = format!("{value:.5}");
    let trimmed = rounded.trim_end_matches('0').trim_end_matches('.');
    if trimmed.contains('.') {
        trimmed.to_owned()
    } else {
        format!("{trimmed}.0")
    }
}
fn point(value: [f64; 2]) -> String {
    format!("[{},{}]", number(value[0]), number(value[1]))
}
fn command(command: &Command) -> String {
    match command {
        Command::Move(p) => format!("Move({})", point(*p)),
        Command::Line(p) => format!("Line({})", point(*p)),
        Command::Cubic(a, b, c) => format!("Cubic({},{},{})", point(*a), point(*b), point(*c)),
        Command::Quadratic(a, b) => format!("Quadratic({},{})", point(*a), point(*b)),
        Command::Close => "Close".to_owned(),
    }
}
fn generate(root: &Path) -> Result<String, String> {
    let mut files: Vec<_> = std::fs::read_dir(root.join("design/icons"))
        .map_err(|error| error.to_string())?
        .filter_map(Result::ok)
        .map(|item| item.path())
        .filter(|p| p.extension().is_some_and(|ext| ext == "svg"))
        .collect();
    files.sort();
    if files.is_empty() {
        return Err("no source icons".into());
    }
    let mut entries = Vec::new();
    for file in files {
        let name = file
            .file_stem()
            .and_then(|name| name.to_str())
            .ok_or("icon filename")?
            .to_owned();
        if !name.chars().all(|ch| ch.is_ascii_lowercase() || ch == '-') {
            return Err("icon names must be lowercase English kebab-case".into());
        }
        let text = std::fs::read_to_string(&file).map_err(|error| error.to_string())?;
        let cmds = svg::parse(&text).map_err(|error| format!("{}: {error}", file.display()))?;
        entries.push((name, cmds));
    }
    let mut out=String::from("// @generated by cargo xtask icons from design/icons/*.svg; do not edit.\nuse crate::icon::PathCommand;\nuse PathCommand::{Move,Line,Cubic,Quadratic,Close};\n\n/// Original Forja stroke icons, on a 24 by 24 grid.\n#[derive(Clone,Copy,Debug,PartialEq,Eq,Hash)]\npub enum Icon {\n");
    for (name, _) in &entries {
        out.push_str(&format!("    {},\n", variant(name)));
    }
    out.push_str("}\n\nimpl Icon {\n    /// All icons in stable source-name order.\n    pub const ALL: &'static [Self] = &[\n");
    for (name, _) in &entries {
        out.push_str(&format!("        Self::{},\n", variant(name)));
    }
    out.push_str("    ];\n    /// Stable Forja metadata id (not a font glyph).\n    pub fn id(self) -> &'static str { match self {\n");
    for (name, _) in &entries {
        out.push_str(&format!("        Self::{} => \"{name}\",\n", variant(name)));
    }
    out.push_str("    }}\n    /// Resolves a Forja icon id.\n    pub fn from_id(id: &str) -> Option<Self> { Self::ALL.iter().copied().find(|icon| icon.id() == id) }\n    pub(crate) fn commands(self) -> &'static [PathCommand] { ICONS[self as usize] }\n}\n\n#[rustfmt::skip]\nstatic ICONS: &[&[PathCommand]] = &[\n");
    for (name, cmds) in &entries {
        out.push_str(&format!(
            "    &[{}], // {name}\n",
            cmds.iter().map(command).collect::<Vec<_>>().join(",")
        ));
    }
    out.push_str("];\n");
    Ok(out)
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn checked_in_table_matches_all_svg_sources() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        assert_eq!(
            generate(root).unwrap(),
            // A Windows checkout with core.autocrlf turns LF into CRLF; compare the text only.
            std::fs::read_to_string(root.join("crates/ui-kit/src/icons_gen.rs"))
                .unwrap()
                .replace("\r\n", "\n"),
            "run cargo xtask icons"
        );
    }
}
