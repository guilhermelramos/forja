//! Links module crates listed in the `# forja:modules` region of `Cargo.toml`
//! and exposes their direct constructors.
//!
//! `linkme` is the primary discovery mechanism. On targets where its linker
//! section is not gathered (Windows GNU), the generated [`linked`] function
//! still returns every module because the macro also exports
//! `__forja_module()`.

use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=Cargo.toml");
    let manifest_path = Path::new(env!("CARGO_MANIFEST_DIR")).join("Cargo.toml");
    let manifest = std::fs::read_to_string(&manifest_path)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", manifest_path.display()));
    let mut externs = String::from("// Generated by build.rs from the # forja:modules region.\n");
    let mut factories: Vec<String> = Vec::new();
    let mut in_region = false;
    for line in manifest.lines() {
        let trimmed = line.trim();
        if trimmed == "# forja:modules:start" {
            in_region = true;
            continue;
        }
        if trimmed == "# forja:modules:end" {
            in_region = false;
            continue;
        }
        if !in_region || trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some((name, _)) = trimmed.split_once('=') else {
            continue;
        };
        let crate_name = name.trim().replace('-', "_");
        if crate_name.is_empty() {
            continue;
        }
        externs.push_str(&format!(
            "#[allow(unused_extern_crates)]\nextern crate {crate_name};\n"
        ));
        factories.push(format!("{crate_name}::__forja_module()"));
    }
    let list = if factories.is_empty() {
        "Vec::new()".to_owned()
    } else {
        format!("vec![{}]", factories.join(", "))
    };
    let generated = format!(
        "{externs}\n\
         /// One constructor per linked module.\n\
         pub fn linked() -> Vec<Box<dyn forja_kernel::Module>> {{\n\
             {list}\n\
         }}\n"
    );
    let out = std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    std::fs::write(Path::new(&out).join("modules.rs"), generated)
        .unwrap_or_else(|error| panic!("could not write modules.rs: {error}"));
    embed_icon();
}

/// Puts `design/assets/logo.ico` on the executable as resource 1.
/// Module discovery above is unchanged. `windres` is the GNU toolchain's.
fn embed_icon() {
    if std::env::var("CARGO_CFG_TARGET_OS").ok().as_deref() != Some("windows") {
        return;
    }
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let ico = manifest_dir.join("../../design/assets/logo.ico");
    println!("cargo:rerun-if-changed={}", ico.display());
    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let rc_path = out_dir.join("forja-icon.rc");
    let obj_path = out_dir.join("forja-icon.o");
    let ico_rc = ico.display().to_string().replace('\\', "/");
    std::fs::write(&rc_path, format!("1 ICON \"{ico_rc}\"\n"))
        .unwrap_or_else(|error| panic!("could not write icon rc: {error}"));
    let status = std::process::Command::new("windres")
        .args([
            "--input",
            rc_path.to_str().expect("rc path"),
            "--output",
            obj_path.to_str().expect("obj path"),
            "--output-format",
            "coff",
        ])
        .status()
        .unwrap_or_else(|error| panic!("windres failed to start: {error}"));
    if !status.success() {
        panic!("windres exited with {status}");
    }
    println!("cargo:rustc-link-arg-bins={}", obj_path.display());
}
